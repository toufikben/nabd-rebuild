#!/usr/bin/env python3
"""Generates the app's string tables from l10n/*.json.

    python3 scripts/gen_l10n.py

l10n/languages.json lists the shipped languages; l10n/<code>.json holds every
string for one language, with English (en.json) as the reference key set.
Outputs (never edit them by hand):

  lib/core/l10n/strings/<code>.dart        one const map per language
  lib/core/l10n/languages.dart             the language list and table map
  android/app/src/main/res/values*/strings.xml   from the "android.*" keys

test/i18n_test.dart checks that every language has exactly the English keys,
keeps every {placeholder}, and that these outputs match the JSON.
"""

import json
import os
import re
import sys
import unicodedata
from xml.sax.saxutils import escape

ROOT = os.path.join(os.path.dirname(__file__), '..')
L10N = os.path.join(ROOT, 'l10n')
OUT = os.path.join(ROOT, 'lib', 'core', 'l10n')
RES = os.path.join(ROOT, 'android', 'app', 'src', 'main', 'res')
HEADER = '// GENERATED by scripts/gen_l10n.py from l10n/*.json. Do not edit.\n'


def dart_string(value):
    return "'" + (value.replace('\\', '\\\\').replace("'", "\\'")
                  .replace('$', '\\$').replace('\n', '\\n')) + "'"


def ident(code):
    return 'strings' + ''.join(p.capitalize() for p in code.replace('-', '_').split('_'))


# Bundled families, in the order "automatic" prefers them. A language lists
# only the families that draw every letter of its strings; the rest of the
# scripts (CJK, Indic...) use the phone's own fonts.
FONT_FAMILIES = ['IBMPlexSansArabic', 'Nunito', 'Lora']


def font_coverage():
    from fontTools.ttLib import TTFont  # pip install fonttools
    fonts = os.path.join(ROOT, 'assets', 'fonts')
    return {family: set(TTFont(os.path.join(fonts, f'{family}-Regular.ttf')).getBestCmap())
            for family in FONT_FAMILIES}


def main():
    coverage = font_coverage()
    covering = {}
    languages = json.load(open(os.path.join(L10N, 'languages.json'), encoding='utf-8'))
    reference = json.load(open(os.path.join(L10N, 'en.json'), encoding='utf-8'))
    os.makedirs(os.path.join(OUT, 'strings'), exist_ok=True)
    for lang in languages:
        code = lang['code']
        table = json.load(open(os.path.join(L10N, f'{code}.json'), encoding='utf-8'))
        missing = sorted(set(reference) - set(table))
        extra = sorted(set(table) - set(reference))
        if missing or extra:
            sys.exit(f'{code}.json: missing {missing[:5]} extra {extra[:5]}')
        holes = re.compile(r'\{[a-zA-Z_]+\}')
        broken = [k for k in reference
                  if set(holes.findall(reference[k])) != set(holes.findall(table[k]))
                  or not table[k].strip()]
        if broken:
            sys.exit(f'{code}.json: blank or placeholders differ in {broken[:5]}')
        letters = {ord(c) for v in table.values() for c in v
                   if unicodedata.category(c).startswith('L')}
        covering[code] = [f for f in FONT_FAMILIES if letters <= coverage[f]]
        lines = [HEADER, f'const Map<String, String> {ident(code)} = <String, String>{{']
        for key in reference:  # English order keeps diffs readable
            lines.append(f'  {dart_string(key)}: {dart_string(table[key])},')
        lines.append('};\n')
        with open(os.path.join(OUT, 'strings', f'{code}.dart'), 'w', encoding='utf-8') as f:
            f.write('\n'.join(lines))
        folder = 'values' + (f"-{lang['android']}" if lang['android'] else '')
        os.makedirs(os.path.join(RES, folder), exist_ok=True)
        xml = ['<?xml version="1.0" encoding="utf-8"?>',
               '<!-- GENERATED by scripts/gen_l10n.py from l10n/*.json. Do not edit. -->',
               '<resources>']
        for key in reference:
            if key.startswith('android.'):
                value = escape(table[key]).replace("'", "\\'")
                xml.append(f'    <string name="{key[8:]}">{value}</string>')
        xml.append('</resources>\n')
        with open(os.path.join(RES, folder, 'strings.xml'), 'w', encoding='utf-8') as f:
            f.write('\n'.join(xml))

    imports = '\n'.join(f"import 'strings/{l['code']}.dart';" for l in languages)
    entries = '\n'.join(
        f"  AppLanguage(code: {dart_string(l['code'])}, nativeName: {dart_string(l['name'])}, "
        f"rtl: {'true' if l['rtl'] else 'false'}, speechLocale: {dart_string(l['speech'])}, "
        f"fonts: [{', '.join(dart_string(x) for x in covering[l['code']])}]),"
        for l in languages)
    tables = '\n'.join(f"  {dart_string(l['code'])}: {ident(l['code'])}," for l in languages)
    with open(os.path.join(OUT, 'languages.dart'), 'w', encoding='utf-8') as f:
        f.write(f"""{HEADER}
{imports}

/// A language the app ships, with what the UI needs to know about it.
class AppLanguage {{
  const AppLanguage({{
    required this.code,
    required this.nativeName,
    required this.rtl,
    required this.speechLocale,
    required this.fonts,
  }});

  /// ISO 639-1 code, the key of [stringTables].
  final String code;

  /// The language's name in itself, as shown in the language picker.
  final String nativeName;
  final bool rtl;

  /// The locale id handed to the speech recogniser for dictation.
  final String speechLocale;

  /// Bundled font families that draw every letter of this language, in the
  /// order the automatic font choice prefers. Empty means the system font.
  final List<String> fonts;
}}

const List<AppLanguage> appLanguages = <AppLanguage>[
{entries}
];

const Map<String, Map<String, String>> stringTables = <String, Map<String, String>>{{
{tables}
}};
""")
    print(f'{len(languages)} languages, {len(reference)} keys')


if __name__ == '__main__':
    main()
